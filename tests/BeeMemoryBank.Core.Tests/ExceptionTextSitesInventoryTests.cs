using System.Text;
using System.Text.RegularExpressions;

namespace BeeMemoryBank.Core.Tests;

/// <summary>
/// BMB-306/307 fix round 2 (T3, Q1, M3, P4): the sweep that keeps remote-controlled and exception text off every screen, API answer, status and Warning, kept as a
/// test so that it stays done. Two things are pinned:
/// <list type="number">
/// <item>nothing reads a <c>ReasonPhrase</c> (the reason phrase of an answer is whatever the other host or a proxy in front of it wrote; the message of an
///   <c>HttpRequestException</c> from <c>EnsureSuccessStatusCode</c> carries it too, which is why such failures are told by <c>PeerContactLog.Describe</c> and never by
///   their message);</item>
/// <item><c>docs/design/exception-text-sites.golden.txt</c> lists every source file that uses <c>.Message</c> of an exception (or a failure's message), with a count.
///   A new line is a new place that may show an exception's text: review it against <c>BeeMemoryBank.Sync.FailureText</c> (the one rule: a failure this code threw to be
///   read says its own sentence, everything else is told as a kind of failure) before accepting it with <c>BMB_UPDATE_GOLDEN=1</c>.</item>
/// </list>
/// </summary>
public class ExceptionTextSitesInventoryTests
{
    private static readonly string[] Roots = ["libs", "server", "desktop", "mobile"];

    // ".Message" as a member of something that is not a request, a log entry or a chat message: exceptions and failures. The names that are plain data are excluded.
    private static readonly Regex MessageUse = new(@"(?<![\w\)\]])(?!req\.|request\.|entry\.|e\.At)\b\w[\w?]*\.Message\b", RegexOptions.Compiled);

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "BeeMemoryBank.slnx"))) dir = dir.Parent;
        dir.Should().NotBeNull("the tests run from inside the repository");
        return dir!.FullName;
    }

    private static IEnumerable<string> Sources(string root)
    {
        foreach (var top in Roots)
        {
            var folder = Path.Combine(root, top);
            if (!Directory.Exists(folder)) continue;
            foreach (var file in Directory.EnumerateFiles(folder, "*.cs", SearchOption.AllDirectories))
            {
                var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
                if (relative.Contains("/obj/") || relative.Contains("/bin/")) continue;
                yield return relative;
            }
        }
    }

    private static string Code(string root, string relative) =>
        string.Join('\n', File.ReadAllText(Path.Combine(root, relative)).Split('\n').Select(l => { var i = l.IndexOf("//", StringComparison.Ordinal); return i >= 0 ? l[..i] : l; }));

    [Fact]
    public void NothingReadsAReasonPhrase()
    {
        var root = RepoRoot();
        var readers = Sources(root)
            .Where(r => Regex.IsMatch(Code(root, r), @"\.ReasonPhrase\b"))
            .ToList();

        // The maintenance handlers WRITE a reason phrase into an answer they make up (a fixed sentence of this code); nothing READS the phrase of an answer.
        readers.Should().BeEmpty("a reason phrase is the other host's text: it never reaches a screen, an answer or a log");
    }

    [Fact]
    public void EverySiteThatUsesTheMessageOfAnExceptionIsInTheGolden()
    {
        var root = RepoRoot();
        var actual = new List<string>();
        foreach (var relative in Sources(root).OrderBy(r => r, StringComparer.Ordinal))
        {
            var count = MessageUse.Matches(Code(root, relative)).Count;
            if (count > 0) actual.Add($"{relative} {count}");
        }
        var header = "# GENERATED by ExceptionTextSitesInventoryTests (BMB_UPDATE_GOLDEN=1). Every source file that uses the .Message of an exception or a failure, with the count.\n"
            + "# A new line is a new place that may show an exception's text. The rule (BeeMemoryBank.Sync.FailureText): a failure this code threw to be read says its own\n"
            + "# sentence; everything else (HTTP, sockets, TLS, JSON, base64, crypto, I/O, SQLite, the framework) is told as a kind of failure (PeerContactLog.Describe) and\n"
            + "# its details stay in the node's log. Review the new site against that rule before accepting it.\n";
        var path = Path.Combine(root, "docs", "design", "exception-text-sites.golden.txt");
        var text = header + string.Join("\n", actual) + "\n";
        if (Environment.GetEnvironmentVariable("BMB_UPDATE_GOLDEN") == "1")
        {
            File.WriteAllText(path, text, new UTF8Encoding(false));
            return;
        }
        var expected = File.ReadAllLines(path).Where(l => !l.StartsWith('#') && l.Length > 0).ToList();
        actual.Should().Equal(expected, "docs/design/exception-text-sites.golden.txt names every file that uses an exception's message; regenerate it on purpose after the review");
    }
}
