using System.Text;
using System.Text.RegularExpressions;

namespace BeeMemoryBank.Core.Tests;

/// <summary>
/// BMB-306/307 fix rounds 2 and 3 (T1, G2): the address of a peer has ONE rule at every place that writes it (<c>PeerAddressPolicy.ForStorage</c> / <c>Canonicalize</c>), and
/// this inventory is what keeps it so. <c>docs/design/peer-address-writers.golden.txt</c> lists every source file that assigns a whitelist row's <c>ApiAddress</c> or
/// writes the <c>api_address</c> column, and the test fails when a site is added that the golden does not name (review it against the policy, then regenerate with
/// <c>BMB_UPDATE_GOLDEN=1</c>) and when a file that assigns an address does not go through the policy at all.
/// <para>
/// <see cref="EveryAssignmentOfAPeersAddressIsInANamedMethodWithItsReason"/> goes further: it names the METHOD of every assignment. A running node writes a peer's row only
/// in the three entry points of <c>PeerAddressService</c> (they share the policy, the key on record, the versioned event, idempotency, the loop's reset and the audit
/// line); the replicated events are applied in two named methods of the event applier; and the rest build rows from an authoritative source (the host's answer to a
/// join, a backup, a seed, a replica) that carries its own versions and has no live state to reset. A new writer fails the test until it is added here WITH its reason,
/// which is the review.
/// </para>
/// </summary>
public class PeerAddressWritersInventoryTests
{
    private static readonly (string Kind, Regex Pattern)[] Patterns =
    [
        // An assignment or an object-initializer member; "= null" is a parameter default or a clearing, not an address coming in.
        ("assign", new Regex(@"\bApiAddress\s*=(?![=>])(?!\s*null\b)", RegexOptions.Compiled)),
        // The column in an INSERT's column list, or SET api_address = @param.
        ("sql", new Regex(@"\(\s*node_id\s*,[^)]*\bapi_address\b|\bapi_address\s*=\s*@\w+", RegexOptions.Compiled)),
    ];

    private static readonly string[] Roots = ["libs", "server", "desktop", "mobile", "tools"];

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "BeeMemoryBank.slnx"))) dir = dir.Parent;
        dir.Should().NotBeNull("the tests run from inside the repository");
        return dir!.FullName;
    }

    private static IEnumerable<string> Sources(string root)
    {
        foreach (var top in Roots)
        {
            var folder = Path.Combine(root, top);
            if (!Directory.Exists(folder)) continue;
            foreach (var file in Directory.EnumerateFiles(folder, "*.cs", SearchOption.AllDirectories))
            {
                var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
                if (relative.Contains("/obj/") || relative.Contains("/bin/")) continue;
                yield return relative;
            }
        }
    }

    private static string Code(string root, string relative) =>
        string.Join('\n', File.ReadAllText(Path.Combine(root, relative)).Split('\n').Select(l => { var i = l.IndexOf("//", StringComparison.Ordinal); return i >= 0 ? l[..i] : l; }));

    private static List<string> FindSites(string root)
    {
        var lines = new List<string>();
        foreach (var relative in Sources(root).OrderBy(r => r, StringComparer.Ordinal))
        {
            var code = Code(root, relative);
            foreach (var (kind, pattern) in Patterns)
            {
                var count = pattern.Matches(code).Count;
                if (count > 0) lines.Add($"{relative} {kind} {count}");
            }
        }
        return lines;
    }

    [Fact]
    public void EverySiteThatWritesAPeersAddressIsInTheGolden()
    {
        var root = RepoRoot();
        var actual = FindSites(root);
        var header = "# GENERATED by PeerAddressWritersInventoryTests (BMB_UPDATE_GOLDEN=1). Every source file that writes the address of a whitelist row, by kind and count:\n"
            + "#   assign  an assignment or object-initializer member ApiAddress = ... (the file must go through PeerAddressPolicy: ForStorage or Canonicalize)\n"
            + "#   sql     the api_address column in an INSERT or an UPDATE (the repository layer, and the scratch rows a backup is verified in)\n"
            + "# A new line is a new writer of a peer's address: review it against the one policy before accepting it.\n";
        var path = Path.Combine(root, "docs", "design", "peer-address-writers.golden.txt");
        var text = header + string.Join("\n", actual) + "\n";
        if (Environment.GetEnvironmentVariable("BMB_UPDATE_GOLDEN") == "1")
        {
            File.WriteAllText(path, text, new UTF8Encoding(false));
            return;
        }
        var expected = File.ReadAllLines(path).Where(l => !l.StartsWith('#') && l.Length > 0).ToList();
        actual.Should().Equal(expected, "docs/design/peer-address-writers.golden.txt names every site that writes a peer's address; regenerate it on purpose after the review");
    }

    private sealed record Writer(string File, string Method, string Reason);

    private const string Live = "a running node's row, through the one service: policy, key on record, versioned event, idempotency, loop reset, audit";
    private const string Event = "a replicated event: policy (AddressFromEvent), last-writer-wins by row version, the key is never replaced, the loop is reset when the place moved";
    private const string Source = "a row built from an authoritative source that carries its own versions (nothing live to reset, no event to publish): the address goes through PeerAddressPolicy.ForStorage";

    /// <summary>Every method that assigns a peer's address, with why it may. The first block is the invariant-bearing service, the second the event applier.</summary>
    private static readonly Writer[] Writers =
    [
        new("libs/BeeMemoryBank.Sync/PeerAddressService.cs", "ChangeAsync", "a person's change, probed first: " + Live),
        new("libs/BeeMemoryBank.Sync/PeerAddressService.cs", "ApplyProofAsync", "an existing peer proved itself (re-join, pair code, hub probe): " + Live),
        new("libs/BeeMemoryBank.Sync/PeerAddressService.cs", "AdmitAsync", "a new peer's row: " + Live),
        new("libs/BeeMemoryBank.Sync/EventApplier.Whitelist.cs", "ApplyWhitelistAddAsync", "add (and re-activation) from another node: " + Event),
        new("libs/BeeMemoryBank.Sync/EventApplier.Whitelist.cs", "ApplyWhitelistUpdateAsync", "update from another node: " + Event),
        new("libs/BeeMemoryBank.Blind.PhoneClient/Sync/Blind/BlindPhoneReplicaClient.cs", "BuildAndSwitchDatabaseAsync", "the phone's replica of a blind package: " + Source),
        new("libs/BeeMemoryBank.Blind.PhoneClient/Sync/Blind/BlindPhoneReplicaClient.Format2.cs", "InstallFormat2Async", "the phone's replica of a format-2 package: " + Source),
        new("mobile/BeeMemoryBank.Mobile/Services/NodeSetupService.cs", "JoinAsync", "the joining phone builds its first whitelist from the host's answer: " + Source),
        new("server/BeeMemoryBank.Cli/Commands/JoinCommand.cs", "HandleAsync", "the command-line join builds the host's row and the inherited peers from its answer: " + Source),
        new("server/BeeMemoryBank.Api/Endpoints/InitEndpoints.cs", "MapInitEndpoints", "the web join builds the host's row and the inherited peers from its answer: " + Source),
        new("server/BeeMemoryBank.Api/Endpoints/BlindRestoreEndpoints.cs", "MapBlindRestoreEndpoints", "a restored device claims a blind node with a one-time restore code, which replaces its row wholesale (the key too); it is no peer's change of address: " + Source),
        new("server/BeeMemoryBank.Api/Services/Blind/BlindSeedService.cs", "BuildDatabaseAsync", "the whitelist of the database a seed builds, from the package: " + Source),
        new("server/BeeMemoryBank.Api/Services/Blind/BlindSeedService.cs", "ApplyFirstSeedStandingAsync", "the producer's row after a first seed, vouched for by the pair code's secret: " + Source),
        new("server/BeeMemoryBank.Api/Services/Blind/BlindSeedService.Format2.cs", "ImportFullAsync", "the whitelist a format-2 full package carries: " + Source),
        new("server/BeeMemoryBank.Api/Services/Recovery/RecoveryRestoreService.cs", "WritePeersAsync", "the peers of the recovered mesh, written by a recovery restore: " + Source),
    ];

    /// <summary>The columns of a row are written by the repository from what it is given, and by the scratch rows a backup is verified in.</summary>
    private static readonly string[] SqlWriters =
    [
        "libs/BeeMemoryBank.Storage/Sqlite/WhitelistRepository.cs",            // persists the row it is given: every caller above hands it a canonical address
        "server/BeeMemoryBank.Api/Services/BlindPhone/AndroidBackupRestoreSource.cs",   // scratch rows of the database a backup is verified in; they are never read as peers
    ];

    private static readonly Regex MemberDeclaration = new(
        @"^( {4})(?:\[[^\]]*\]\s*)*(?:(?:public|private|internal|protected|static|async|override|virtual|sealed|extern|partial|new|unsafe)\s+)+[^=;(){}]*?\b(\w+)\s*(?:<[^>]*>)?\s*\(",
        RegexOptions.Compiled);

    /// <summary>The (file, method) of every assignment of a peer's address in the production sources.</summary>
    private static List<(string File, string Method)> AssignmentSites(string root)
    {
        var sites = new List<(string File, string Method)>();
        foreach (var relative in Sources(root).OrderBy(r => r, StringComparer.Ordinal))
        {
            var code = Code(root, relative);
            if (!Patterns[0].Pattern.IsMatch(code)) continue;
            var lines = code.Split('\n');
            var method = "(none)";
            for (var n = 0; n < lines.Length; n++)
            {
                if (MemberDeclaration.Match(lines[n]) is { Success: true } declaration) method = declaration.Groups[2].Value;
                if (Patterns[0].Pattern.IsMatch(lines[n])) sites.Add((relative, method));
            }
        }
        return sites.Distinct().ToList();
    }

    [Fact]
    public void EveryAssignmentOfAPeersAddressIsInANamedMethodWithItsReason()
    {
        var root = RepoRoot();
        var actual = AssignmentSites(root).Select(site => $"{site.File} :: {site.Method}").OrderBy(x => x, StringComparer.Ordinal).ToList();
        var allowed = Writers.Select(w => $"{w.File} :: {w.Method}").OrderBy(x => x, StringComparer.Ordinal).ToList();

        actual.Should().Equal(allowed,
            "a peer's address is assigned only in the methods PeerAddressWritersInventoryTests.Writers names, each with the reason it may: a new writer is added there only after it has been "
            + "reviewed against the rules the service shares (policy, key on record, versioned event, idempotency, loop reset, audit) or shown to be a row built from an authoritative source");
        Writers.Should().OnlyContain(w => w.Reason.Length > 40, "every allowed method says why");
        var sql = FindSites(root).Where(line => line.Contains(" sql ")).Select(line => line.Split(' ')[0]).ToList();
        sql.Should().Equal(SqlWriters.OrderBy(x => x, StringComparer.Ordinal), "the columns are written only by the repository and the backup's scratch rows");
    }

    [Fact]
    public void TheThreeLiveWritersApplyThePolicyBeforeTheyLogOrWrite()
    {
        // The order is the point: a refused address must leave nothing behind - no event, no row, no audit line.
        var service = File.ReadAllText(Path.Combine(RepoRoot(), "libs", "BeeMemoryBank.Sync", "PeerAddressService.cs")).Replace("\r\n", "\n");
        foreach (var method in new[] { "ChangeAsync", "ApplyProofAsync", "AdmitAsync" })
        {
            var start = service.IndexOf($"public async Task<PeerAddressResult> {method}(", StringComparison.Ordinal);
            start.Should().BeGreaterThan(0, method);
            var end = service.IndexOf("\n    }\n", start, StringComparison.Ordinal);
            var body = service[start..end];
            var policy = body.IndexOf("PeerAddressPolicy.Canonicalize(", StringComparison.Ordinal);
            var logged = body.IndexOf("events.Log", StringComparison.Ordinal);
            var written = body.IndexOf("whitelist.UpdateAsync(", StringComparison.Ordinal) is var u and >= 0 ? u : body.IndexOf("whitelist.CreateAsync(", StringComparison.Ordinal);
            policy.Should().BeGreaterThan(0, $"{method} applies the policy");
            logged.Should().BeGreaterThan(policy, $"{method} logs the event only after the policy has accepted the address");
            (written < 0 ? body.IndexOf("write(entry)", StringComparison.Ordinal) : written).Should().BeGreaterThan(logged, $"{method} writes the row after the event minted its version");
        }
    }

    [Fact]
    public void EveryFileThatAssignsAPeersAddressGoesThroughThePolicy()
    {
        var root = RepoRoot();
        var withoutPolicy = Sources(root)
            .Where(r => Patterns[0].Pattern.IsMatch(Code(root, r)) && !Code(root, r).Contains("PeerAddressPolicy.", StringComparison.Ordinal))
            .ToList();

        withoutPolicy.Should().BeEmpty("a peer's address is stored in the form PeerAddressPolicy.ForStorage makes of it (or refused), at every boundary that writes it");
    }
}
