using System.Text;
using System.Text.RegularExpressions;

namespace BeeMemoryBank.Core.Tests.Sealed;

/// <summary>
/// The inventory of docs/design/step-b-spec.md 11.2: <c>docs/design/key-slot-writers.golden.txt</c> lists every code site that inserts into
/// <c>tbl_key_slot</c>, and this test greps the sources and fails when a site is added that the golden does not name. A new writer has to be
/// reviewed against the scope list of 11.2 (nothing but the explicit enable call may create a <c>server_auto_unlock</c> slot) and against the
/// write protocol of 4.3 (a door written before the commit) before the golden is changed on purpose (<c>BMB_UPDATE_GOLDEN=1</c>).
/// </summary>
public class KeySlotWritersInventoryTests
{
    // A raw INSERT into the table; a call of CreateAsync on anything called ...slot...; the door-aware helper that wraps it.
    private static readonly (string Kind, Regex Pattern)[] Patterns =
    [
        ("sql-insert", new Regex(@"INSERT\s+(OR\s+\w+\s+)?INTO\s+tbl_key_slot\b", RegexOptions.IgnoreCase | RegexOptions.Compiled)),
        ("repo-create", new Regex(@"\b\w*[Ss]lots?\w*\s*\.\s*CreateAsync\s*\(", RegexOptions.Compiled)),
        ("slot-doors", new Regex(@"\bSlotDoors\s*\.\s*CreateSlotAsync\s*\(", RegexOptions.Compiled)),
    ];

    private static readonly string[] Roots = ["libs", "server", "desktop", "mobile", "tools"];

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "BeeMemoryBank.slnx"))) dir = dir.Parent;
        dir.Should().NotBeNull("the tests run from inside the repository");
        return dir!.FullName;
    }

    private static IEnumerable<string> Sources(string root)
    {
        foreach (var top in Roots)
        {
            var folder = Path.Combine(root, top);
            if (!Directory.Exists(folder)) continue;
            foreach (var file in Directory.EnumerateFiles(folder, "*.cs", SearchOption.AllDirectories))
            {
                var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
                if (relative.Contains("/obj/") || relative.Contains("/bin/")) continue;
                yield return relative;
            }
        }
    }

    internal static List<string> FindSites(string root)
    {
        var lines = new List<string>();
        foreach (var relative in Sources(root).OrderBy(r => r, StringComparer.Ordinal))
        {
            var text = File.ReadAllText(Path.Combine(root, relative));
            // Comments do not write rows: line comments and XML docs are dropped before matching.
            var code = string.Join('\n', text.Split('\n').Select(l => { var i = l.IndexOf("//", StringComparison.Ordinal); return i >= 0 ? l[..i] : l; }));
            foreach (var (kind, pattern) in Patterns)
            {
                var count = pattern.Matches(code).Count;
                if (count > 0) lines.Add($"{relative} {kind} {count}");
            }
        }
        return lines;
    }

    [Fact]
    public void EverySiteThatInsertsAKeySlotIsInTheGolden()
    {
        var root = RepoRoot();
        var actual = FindSites(root);
        var header = "# GENERATED by KeySlotWritersInventoryTests (BMB_UPDATE_GOLDEN=1). Every source file that inserts a row into tbl_key_slot, by kind and count:\n"
            + "#   sql-insert  a raw INSERT INTO tbl_key_slot\n"
            + "#   repo-create a call of CreateAsync on a key-slot repository (the plain call)\n"
            + "#   slot-doors  SlotDoors.CreateSlotAsync, the call that also writes the pending door of a sealed node (docs/design/step-b-spec.md 4.3)\n"
            + "# A new line is a new writer of key slots: review it against 11.2 (nothing but the explicit enable call creates a server_auto_unlock slot)\n"
            + "# and 4.3 (a door is written before the sealed commit) before accepting it.\n";
        var path = Path.Combine(root, "docs", "design", "key-slot-writers.golden.txt");
        var text = header + string.Join("\n", actual) + "\n";
        if (Environment.GetEnvironmentVariable("BMB_UPDATE_GOLDEN") == "1")
        {
            File.WriteAllText(path, text, new UTF8Encoding(false));
            return;
        }
        var expected = File.ReadAllLines(path).Where(l => !l.StartsWith('#') && l.Length > 0).ToList();
        actual.Should().Equal(expected, "docs/design/key-slot-writers.golden.txt names every site that inserts a key slot; regenerate it on purpose after the review of 11.2");
    }

    [Fact]
    public void OnlyTheEnableServiceNamesTheServerSlotType_AsAWriter()
    {
        // No other code may build a slot of the server type: the scope list of 11.2 says nothing but the explicit enable call creates one.
        var root = RepoRoot();
        var writers = Sources(root)
            .Where(r => Regex.IsMatch(File.ReadAllText(Path.Combine(root, r)), @"SlotType\s*=\s*""server_auto_unlock""|SlotType\s*=\s*ServerAutoUnlockService\.SlotType"))
            .ToList();
        writers.Should().Equal(["libs/BeeMemoryBank.Infrastructure/AutoUnlock/ServerAutoUnlockService.cs"]);
    }

    [Fact]
    public void NoConfigurationKeyOrFlagEnablesTheCheckbox()
    {
        // The only environment variable the checkbox reads names a key file; nothing turns it on (spec 11.2 item 4).
        var root = RepoRoot();
        var readers = Sources(root)
            .Where(r => File.ReadAllText(Path.Combine(root, r)).Contains("BMB_AUTO_UNLOCK", StringComparison.Ordinal))
            .ToList();
        readers.Should().Equal(["libs/BeeMemoryBank.Infrastructure/AutoUnlock/ServerAutoUnlockService.cs"]);
        var text = File.ReadAllText(Path.Combine(root, "libs/BeeMemoryBank.Infrastructure/AutoUnlock/ServerAutoUnlockService.cs"));
        Regex.Matches(text, @"BMB_AUTO_UNLOCK_\w+").Select(m => m.Value).Distinct().Should().Equal(["BMB_AUTO_UNLOCK_KEY_FILE"]);
    }

    [Fact]
    public void BMB_HOST_ROLE_IsSetInOnePlace_TheDesktopsNodeStart()
    {
        var root = RepoRoot();
        var setters = Sources(root)
            .Where(r => Regex.IsMatch(File.ReadAllText(Path.Combine(root, r)), @"EnvironmentVariables\[""BMB_HOST_ROLE""\]|SetEnvironmentVariable\(\s*""BMB_HOST_ROLE"""))
            .ToList();
        setters.Should().Equal(["desktop/BeeMemoryBank.Desktop/Services/NodeLifecycleService.cs"]);

        // Not a compose file, not the Dockerfile, not .env.example, not an installer script.
        foreach (var relative in new[] { "Dockerfile", "docker-compose.yml", "docker-compose.image.yml", "docker-compose.reverse-proxy.yml", ".env.example", "docker-entrypoint.sh" })
        {
            var path = Path.Combine(root, relative);
            if (File.Exists(path)) File.ReadAllText(path).Should().NotContain("BMB_HOST_ROLE", relative);
        }
        foreach (var file in Directory.EnumerateFiles(Path.Combine(root, "installers"), "*", SearchOption.AllDirectories).Where(f => !f.Contains("/obj/") && !f.Contains("\\obj\\")))
        {
            var info = new FileInfo(file);
            if (info.Length > 2_000_000) continue;
            if (File.ReadAllText(file).Contains("BMB_HOST_ROLE", StringComparison.Ordinal)) Assert.Fail($"{Path.GetRelativePath(root, file)} must not set BMB_HOST_ROLE");
        }
    }
}
