using System.Collections;
using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Serialization.Metadata;
using BeeMemoryBank.Core.Models;
using BeeMemoryBank.Sync.Metadata;

namespace BeeMemoryBank.Sync.Tests;

/// <summary>
/// The clear-field allow-list of protocol 4 (docs/design/step-a-spec.md 3.11): every name that travels readable once
/// metadata is encrypted. For <c>sealed</c>, the outer event's properties as the wire serialises them and the envelope's
/// properties; for each control type, the properties of its payload as the serialiser writes them (nested records
/// included). Adding a property to a control payload or to the envelope fails here until
/// <c>docs/design/protocol4-clear-fields.golden.txt</c> is updated on purpose (BMB_UPDATE_GOLDEN=1, then review the
/// diff): that is the moment to ask "is this metadata?".
/// </summary>
public class ClearFieldGoldenTests
{
    private const string GoldenFile = "docs/design/protocol4-clear-fields.golden.txt";
    private static readonly JsonSerializerOptions Wire = new(JsonSerializerDefaults.Web);

    /// <summary>The payload record of every control type, as its writer serialises it.</summary>
    private static readonly Dictionary<string, Type> ControlPayloads = new(StringComparer.Ordinal)
    {
        [EventTypes.WhitelistAdd] = typeof(WhitelistAddPayload),
        [EventTypes.WhitelistRevoke] = typeof(WhitelistRevokePayload),
        [EventTypes.WhitelistUpdate] = typeof(WhitelistUpdatePayload),
        [EventTypes.SnapshotCheckpoint] = typeof(SnapshotCheckpointPayload),
        [EventTypes.RestoreNetwork] = typeof(RestoreNetworkEventPayload),
        [EventTypes.DekRotationProposed] = typeof(DekRotationProposedPayload),
        [EventTypes.DekRotationCommit] = typeof(DekRotationCommitPayload),
        [EventTypes.MasterPasswordChanged] = typeof(MasterPasswordChangedPayload),
        [EventTypes.RecoveryBoxSet] = typeof(RecoveryBoxSetPayload),
        [EventTypes.RecoveryBoxRetire] = typeof(RecoveryBoxRetirePayload),
        [EventTypes.RetiredLinkSet] = typeof(RetiredLinkSetPayload),
        [EventTypes.StateAnchor] = typeof(StateAnchorPayload),
        [EventTypes.SealedSecretSet] = typeof(SealedSecretSetPayload),
        [EventTypes.MetadataKeySet] = typeof(MetadataKeySetPayload),
        [EventTypes.MetadataActivation] = typeof(MetadataActivationPayload),
    };

    [Fact]
    public void EveryControlType_HasItsPayloadListed()
    {
        ControlPayloads.Keys.Should().BeEquivalentTo(EventClasses.Control,
            "a new control type travels in clear: list its payload here so its fields join the golden file");
    }

    [Fact]
    public void TheFieldsThatTravelInClear_AreExactlyTheGoldenOnes()
    {
        var actual = Lines().ToList();
        var file = Path.Combine(RepoRoot(), GoldenFile.Replace('/', Path.DirectorySeparatorChar));
        if (Environment.GetEnvironmentVariable("BMB_UPDATE_GOLDEN") == "1")
        {
            File.WriteAllText(file,
                "# GENERATED by ClearFieldGoldenTests (BMB_UPDATE_GOLDEN=1). What travels readable in protocol 4\n" +
                "# (docs/design/step-a-spec.md 3.11): the sealed event's outer properties and envelope, and the payload of every\n" +
                "# control event. A new line here is a new clear field: ask whether it is metadata before accepting it.\n" +
                string.Join("\n", actual) + "\n");
            return;
        }
        File.ReadAllLines(file).Select(l => l.Trim()).Where(l => l.Length > 0 && !l.StartsWith('#')).Should().Equal(actual,
            "a field that travels in clear was added or removed; regenerate with BMB_UPDATE_GOLDEN=1 and review the diff");
    }

    private static IEnumerable<string> Lines()
    {
        // One sample sealed event, serialised as GET /api/sync/events and the push body serialise it.
        var author = new StepAAuthor();
        author.NewKey(RandomNumberGenerator.GetBytes(32));
        var sample = author.Sealed(EventTypes.FolderCreate, null, StepAAuthor.FolderCreate(Guid.NewGuid(), "/Sample", "Sample"));
        using var outer = JsonDocument.Parse(JsonSerializer.Serialize(sample, Wire));
        foreach (var name in outer.RootElement.EnumerateObject().Select(p => p.Name).Order(StringComparer.Ordinal))
            yield return $"sealed outer {name}";
        using var envelope = JsonDocument.Parse(sample.Payload);
        foreach (var name in envelope.RootElement.EnumerateObject().Select(p => p.Name).Order(StringComparer.Ordinal))
            yield return $"sealed envelope {name}";

        foreach (var (type, payload) in ControlPayloads.OrderBy(c => c.Key, StringComparer.Ordinal))
            foreach (var name in PropertyNames(payload, "").Order(StringComparer.Ordinal))
                yield return $"control {type} {name}";
    }

    /// <summary>The names the default serialiser writes for <paramref name="type"/>, nested records as dotted paths.</summary>
    private static IEnumerable<string> PropertyNames(Type type, string prefix)
    {
        foreach (var property in JsonSerializerOptions.Default.GetTypeInfo(type).Properties)
        {
            var name = prefix + property.Name;
            yield return name;
            if (Nested(property.PropertyType) is { } inner)
                foreach (var nested in PropertyNames(inner.Type, name + inner.Marker + "."))
                    yield return nested;
        }
    }

    /// <summary>A record of this product inside a payload (directly, as dictionary values or as list items), else null.</summary>
    private static (Type Type, string Marker)? Nested(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        if (IsOwn(type)) return (type, "");
        if (type.IsGenericType && type.GetGenericArguments() is { Length: 2 } kv && typeof(IDictionary).IsAssignableFrom(type) && IsOwn(kv[1]))
            return (kv[1], "{}");
        var item = type.IsArray ? type.GetElementType() : type.IsGenericType && typeof(IEnumerable).IsAssignableFrom(type) ? type.GetGenericArguments()[0] : null;
        return item is not null && IsOwn(item) ? (item, "[]") : null;
    }

    private static bool IsOwn(Type type) =>
        type.IsClass && type != typeof(string) && type.Namespace?.StartsWith("BeeMemoryBank", StringComparison.Ordinal) == true;

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, "BeeMemoryBank.slnx"))) dir = dir.Parent;
        return dir?.FullName ?? throw new InvalidOperationException("The tests run from inside the repository.");
    }
}
