using System.Security.Cryptography;
using System.Text;
using BeeMemoryBank.Storage.Boot;
using BeeMemoryBank.Storage.Sealed;
using BeeMemoryBank.Storage.Sqlite;
using Dapper;

namespace BeeMemoryBank.Storage.Tests.Boot;

/// <summary>
/// Red tests 15.2.1 (docs/design/step-b-spec.md): the boot schema is exactly the allow-list, the boot whitelist has every column of the
/// vault's, the boot ledger and the vault ledger never see each other. Golden: docs/design/boot-store.golden.txt, docs/boot-migrations.golden.txt;
/// regenerate after an INTENDED change with BMB_UPDATE_GOLDEN=1.
/// </summary>
public class BootStoreTests : IDisposable
{
    private readonly string _dir = Path.Combine(Path.GetTempPath(), "bmb_boot_" + Guid.NewGuid().ToString("N"));

    public BootStoreTests() => Directory.CreateDirectory(_dir);

    public void Dispose()
    {
        try { Directory.Delete(_dir, true); } catch (IOException) { }
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "BeeMemoryBank.slnx"))) dir = dir.Parent;
        dir.Should().NotBeNull("the tests run from inside the repository");
        return dir!.FullName;
    }

    private BootStore NewStore(string name = "beememorybank.boot.db") => new(Path.Combine(_dir, name));

    private static void CheckGolden(string relativePath, string actual)
    {
        var path = Path.Combine(RepoRoot(), relativePath);
        if (Environment.GetEnvironmentVariable("BMB_UPDATE_GOLDEN") == "1")
        {
            File.WriteAllText(path, actual, new UTF8Encoding(false));
            return;
        }
        actual.Should().Be(File.ReadAllText(path).Replace("\r\n", "\n"), $"{relativePath} is the contract; change it on purpose");
    }

    [Fact]
    public async Task TheBootSchemaEqualsTheAllowListGolden()
    {
        var store = NewStore();
        await store.EnsureCreatedAsync();

        using var connection = store.Connections.Open();
        var lines = new List<string>();
        var tables = (await connection.QueryAsync<string>(
            "SELECT name FROM sqlite_schema WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")).ToList();
        foreach (var table in tables)
            foreach (var column in await connection.QueryAsync<(string Name, string Type)>($"SELECT name, type FROM pragma_table_info('{table}')"))
                lines.Add($"{table}.{column.Name} {column.Type}");
        lines.Sort(StringComparer.Ordinal);

        var header = "# GENERATED by BootStoreTests (BMB_UPDATE_GOLDEN=1). Every table and column (name and declared type) of the boot store,\n"
            + "# sorted. A new line is a new column in the one plain file a sealed node reads before unlock: ask \"is this metadata?\" before\n"
            + "# accepting it (docs/design/step-b-spec.md 2.3, Appendix B).\n";
        CheckGolden("docs/design/boot-store.golden.txt", header + string.Join("\n", lines) + "\n");
    }

    [Fact]
    public void TheBootMigrationManifestEqualsItsGolden()
    {
        var assembly = typeof(BootMigrationRunner).Assembly;
        var lines = assembly.GetManifestResourceNames()
            .Where(n => n.StartsWith(BootMigrationRunner.ResourcePrefix, StringComparison.Ordinal) && n.EndsWith(".sql", StringComparison.OrdinalIgnoreCase))
            .OrderBy(n => n, StringComparer.Ordinal)
            .Select(n =>
            {
                using var stream = assembly.GetManifestResourceStream(n)!;
                using var ms = new MemoryStream();
                stream.CopyTo(ms);
                return n + " " + Convert.ToHexString(SHA256.HashData(ms.ToArray())).ToLowerInvariant();
            }).ToList();
        lines.Should().NotBeEmpty();
        CheckGolden("docs/boot-migrations.golden.txt", string.Join("\n", lines) + "\n");
    }

    [Fact]
    public void TheEmbeddedBootSqlIsByteForByteTheSpecAppendix()
    {
        // Appendix B.1 is the contract; the golden pins the bytes, this pins the text against the specification itself.
        var spec = File.ReadAllText(Path.Combine(RepoRoot(), "docs", "design", "step-b-spec.md")).Replace("\r\n", "\n");
        var start = spec.IndexOf("### B.1 ", StringComparison.Ordinal);
        var from = spec.IndexOf("```sql\n", start, StringComparison.Ordinal) + "```sql\n".Length;
        var to = spec.IndexOf("\n```\n", from, StringComparison.Ordinal);
        var expected = spec[from..to] + "\n";

        using var stream = typeof(BootMigrationRunner).Assembly.GetManifestResourceStream(BootMigrationRunner.ResourcePrefix + "B001_boot_store.sql")!;
        using var reader = new StreamReader(stream, new UTF8Encoding(false));
        reader.ReadToEnd().Should().Be(expected);
    }

    [Fact]
    public async Task TheBootWhitelistHasEveryColumnOfTheVaultsWhitelist()
    {
        var store = NewStore();
        await store.EnsureCreatedAsync();
        using var vault = DbConnectionFactory.CreateInMemory("bmb_boot_columns_" + Guid.NewGuid().ToString("N"));
        await new MigrationRunner(vault).RunMigrationsAsync();

        using var vaultConnection = vault.CreateConnection();
        var vaultColumns = (await vaultConnection.QueryAsync<(string Name, string Type)>("SELECT name, type FROM pragma_table_info('tbl_whitelist')")).ToList();
        using var bootConnection = store.Connections.Open();
        var bootColumns = (await bootConnection.QueryAsync<(string Name, string Type)>("SELECT name, type FROM pragma_table_info('tbl_whitelist')")).ToList();

        bootColumns.Select(c => c.Name).Should().BeEquivalentTo(vaultColumns.Select(c => c.Name),
            "a later vault migration that adds a whitelist column must fail here until the boot store gets one (spec 2.3)");
        bootColumns.Select(c => (c.Name, c.Type)).Should().BeEquivalentTo(vaultColumns.Select(c => (c.Name, c.Type)));
    }

    [Fact]
    public async Task TheBootLedgerIsSeparateFromTheVaultsInBothDirections()
    {
        var store = NewStore();
        await store.EnsureCreatedAsync();

        using (var boot = store.Connections.Open())
        {
            (await boot.QueryAsync<string>("SELECT name FROM sqlite_schema WHERE name = 'tbl_migration'")).Should().BeEmpty(
                "the boot store has its own ledger and the vault's runner never wrote into it");
            (await boot.ExecuteScalarAsync<long>("SELECT COUNT(*) FROM tbl_boot_migration")).Should().Be(1);
            (await boot.ExecuteScalarAsync<string>("SELECT filename FROM tbl_boot_migration WHERE version = 1"))
                .Should().Be(BootMigrationRunner.ResourcePrefix + "B001_boot_store.sql");
            (await boot.ExecuteScalarAsync<long>("PRAGMA application_id")).Should().Be(0x424D4253);
            (await boot.ExecuteScalarAsync<string>("PRAGMA journal_mode")).Should().Be("wal");
        }

        // The vault's runner sees none of the boot files: it applies its own set and does not touch tbl_boot_migration.
        using var vault = new DbConnectionFactory(Path.Combine(_dir, "vault.db"));
        await new MigrationRunner(vault).RunMigrationsAsync();
        using (var connection = vault.CreateConnection())
        {
            (await connection.QueryAsync<string>("SELECT name FROM sqlite_schema WHERE name = 'tbl_boot_migration'")).Should().BeEmpty();
            (await connection.QueryAsync<string>("SELECT filename FROM tbl_migration")).Should().OnlyContain(f => !f.Contains(".BootMigrations."));
        }
    }

    [Fact]
    public async Task AGhostRowInTheBootLedgerIsDroppedAndTheCurrentFileAppliedAgain_WithoutTouchingTheVault()
    {
        var store = NewStore();
        await store.EnsureCreatedAsync();
        using (var boot = store.Connections.Open())
        {
            await boot.ExecuteAsync("INSERT INTO tbl_boot_migration (version, filename, applied_at) VALUES (99, 'gone.sql', 'x')");
            await boot.ExecuteAsync("UPDATE tbl_boot_migration SET filename = 'renamed.sql' WHERE version = 1");
            await boot.ExecuteAsync("DROP TABLE tbl_relay_report");
        }

        await store.EnsureCreatedAsync();

        using var after = store.Connections.Open();
        (await after.QueryAsync<(long Version, string Filename)>("SELECT version, filename FROM tbl_boot_migration")).Should().ContainSingle()
            .Which.Should().Be((1L, BootMigrationRunner.ResourcePrefix + "B001_boot_store.sql"));
        (await after.QueryAsync<string>("SELECT name FROM sqlite_schema WHERE name = 'tbl_relay_report'")).Should().ContainSingle("the ghost rule re-applied the idempotent file");
    }

    [Fact]
    public async Task ARunningTwiceChangesNothing_AndAFileThatIsNotABootStoreIsRefused()
    {
        var store = NewStore();
        await store.EnsureCreatedAsync();
        await store.SetMetaAsync(BootMetaKeys.DbkGeneration, "1");
        await store.EnsureCreatedAsync();
        (await store.GetMetaAsync(BootMetaKeys.DbkGeneration)).Should().Be("1");

        var foreign = Path.Combine(_dir, "foreign.db");
        using (var c = new Microsoft.Data.Sqlite.SqliteConnection($"Data Source={foreign};Pooling=False"))
        {
            c.Open();
            c.Execute("CREATE TABLE t (x INTEGER)");
        }
        var bytes = File.ReadAllBytes(foreign);
        var act = async () => await new BootStore(foreign).EnsureCreatedAsync();
        await act.Should().ThrowAsync<InvalidOperationException>();
        File.ReadAllBytes(foreign).Should().Equal(bytes, "nothing was changed");
    }

    [Fact]
    public async Task TheNodeIdOfTheMetaIsWrittenOnceAndNeverChanged()
    {
        var store = NewStore();
        await store.EnsureCreatedAsync();
        var id = Guid.NewGuid().ToString("D");
        await store.SetMetaAsync(BootMetaKeys.NodeId, id);
        await store.SetMetaAsync(BootMetaKeys.NodeId, id); // the same value is fine
        var act = async () => await store.SetMetaAsync(BootMetaKeys.NodeId, Guid.NewGuid().ToString("D"));
        await act.Should().ThrowAsync<InvalidOperationException>();
        (await store.GetMetaAsync(BootMetaKeys.NodeId)).Should().Be(id);
    }

    [Fact]
    public async Task TheBootConnectionIsPlainWal_ForeignKeysOn_BusyTimeout5000_TempStoreFile()
    {
        var store = NewStore();
        await store.EnsureCreatedAsync();
        using var c = store.Connections.Open();
        (await c.ExecuteScalarAsync<long>("PRAGMA foreign_keys")).Should().Be(1);
        (await c.ExecuteScalarAsync<long>("PRAGMA busy_timeout")).Should().Be(5000);
        (await c.ExecuteScalarAsync<long>("PRAGMA temp_store")).Should().Be(1);
        var head = new byte[16];
        using (var file = new FileStream(store.FilePath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete)) file.ReadExactly(head);
        head.AsSpan().SequenceEqual("SQLite format 3\0"u8).Should().BeTrue("the boot store is a plain SQLite file");
        typeof(BootStoreConnectionFactory).GetInterfaces().Should().NotContain(i => i.Name == "IDbConnectionFactory");
    }

    [Fact]
    public void TheDoorHashFollowsTheFormulaOfSpec42()
    {
        // LP(kind) LP("7") LP(slot_type) LP("") ... : recomputed by hand here from the formula in the specification.
        var salt = new byte[] { 1, 2, 3 };
        var wrapped = new byte[] { 9, 8 };
        var iv = new byte[] { 5 };
        using var ms = new MemoryStream();
        void Text(string s) { var b = Encoding.UTF8.GetBytes(s); ms.Write(BitConverter.GetBytes(b.Length)); ms.Write(b); }
        void Bytes(byte[] b) { ms.Write(BitConverter.GetBytes(b.Length)); ms.Write(b); }
        Text("slot"); Text("7"); Text("user"); Text(""); Text(""); Text("65536"); Text("3"); Text("4"); Bytes(salt); Bytes(wrapped); Bytes(iv);
        var expected = Convert.ToHexStringLower(SHA256.HashData(ms.ToArray()));

        BootDoorHash.OfSlot(7, "user", wrapped, iv, salt, 65536, 3, 4).Should().Be(expected);
        BootDoorHash.OfSlot(7, "user", wrapped, iv, salt, 65536, 3, 5).Should().NotBe(expected);
    }
}
